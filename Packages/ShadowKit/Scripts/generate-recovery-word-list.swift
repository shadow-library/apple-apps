import CryptoKit
import Foundation

enum GeneratorError: Error, CustomStringConvertible {
  case usage
  case unreadableInput(path: String, reason: String)
  case digestMismatch(found: String)
  case malformedList(String)

  var description: String {
    switch self {
    case .usage: "Usage: swift generate-recovery-word-list.swift <bip-0039/english.txt> <output.swift>"
    case .unreadableInput(let path, let reason): "Cannot read \(path): \(reason)"
    case .digestMismatch(let found): "english.txt has SHA-256 \(found), not \(expectedDigest)"
    case .malformedList(let reason): "The word list is malformed: \(reason)"
    }
  }
}

let expectedDigest = "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda"
let wordsPerLine = 8

func generate(inputPath: String, outputPath: String) throws {
  let data: Data
  do { data = try Data(contentsOf: URL(fileURLWithPath: inputPath)) } catch { throw GeneratorError.unreadableInput(path: inputPath, reason: "\(error)") }
  let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
  guard digest == expectedDigest else { throw GeneratorError.digestMismatch(found: digest) }
  let words = String(decoding: data, as: UTF8.self).split(separator: "\n", omittingEmptySubsequences: false).dropLast().map(String.init)
  guard words.count == 2048 else { throw GeneratorError.malformedList("expected 2048 words, found \(words.count)") }
  guard words.allSatisfy({ !$0.isEmpty && $0.utf8.allSatisfy { (0x61...0x7A).contains($0) } }) else { throw GeneratorError.malformedList("words must be lowercase ASCII") }

  var lines = [
    "// Generated by Packages/ShadowKit/Scripts/generate-recovery-word-list.swift from the BIP-39 English list (MIT, bitcoin/bips). Do not edit.",
    "",
    "enum RecoveryWordList {",
    "  static let words: [String] = [",
  ]
  for start in stride(from: 0, to: words.count, by: wordsPerLine) {
    lines.append("    " + words[start..<start + wordsPerLine].map { "\"\($0)\"," }.joined(separator: " "))
  }
  lines += ["  ]", "}", ""]
  try lines.joined(separator: "\n").write(toFile: outputPath, atomically: true, encoding: .utf8)
}

do {
  let arguments = CommandLine.arguments.dropFirst()
  guard arguments.count == 2, let inputPath = arguments.first, let outputPath = arguments.last else { throw GeneratorError.usage }
  try generate(inputPath: inputPath, outputPath: outputPath)
} catch {
  FileHandle.standardError.write(Data("\(error)\n".utf8))
  exit(1)
}
